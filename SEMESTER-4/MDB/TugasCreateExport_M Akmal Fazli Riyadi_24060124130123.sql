TRUNCATE TABLE stasiun;
TRUNCATE TABLE kereta;
TRUNCATE TABLE penumpang;

SET FOREIGN_KEY_CHECKS = 1;


-- 1. TABEL KERETA
CREATE TABLE kereta (
    id_kereta VARCHAR(5) PRIMARY KEY,
    nama_kereta VARCHAR(50) NOT NULL,
    kapasitas INT NOT NULL
);

-- 2. TABEL STASIUN
CREATE TABLE stasiun (
    id_stasiun INT PRIMARY KEY AUTO_INCREMENT,
    kode_stasiun VARCHAR(10) UNIQUE NOT NULL,
    nama_stasiun VARCHAR(100) NOT NULL,
    kota VARCHAR(50) NOT NULL,
    wilayah_daop VARCHAR(20) 
);

-- 3. TABEL PENUMPANG
CREATE TABLE penumpang (
    id_penumpang INT PRIMARY KEY AUTO_INCREMENT,
    nik VARCHAR(20) NOT NULL UNIQUE,
    nama_lengkap VARCHAR(100) NOT NULL,
    jenis_kelamin ENUM('L', 'P') NOT NULL,
    no_telepon VARCHAR(15),
    email VARCHAR(30),
    tanggal_daftar DATE
);

-- 4. TABEL JADWAL
CREATE TABLE jadwal (
    id_jadwal INT AUTO_INCREMENT PRIMARY KEY,
    id_kereta VARCHAR(5) NOT NULL,
    id_stasiun_asal INT NOT NULL,
    id_stasiun_tujuan INT NOT NULL,
    waktu_berangkat DATETIME NOT NULL,
    waktu_tiba DATETIME NOT NULL,
    harga INT NOT NULL,
    
    FOREIGN KEY (id_kereta) REFERENCES kereta(id_kereta),
    FOREIGN KEY (id_stasiun_asal) REFERENCES stasiun(id_stasiun),
    FOREIGN KEY (id_stasiun_tujuan) REFERENCES stasiun(id_stasiun)
);

-- 5. TABEL TIKET
CREATE TABLE tiket (
    id_tiket INT PRIMARY KEY AUTO_INCREMENT,
    kode_booking VARCHAR(20) NOT NULL UNIQUE,
    id_penumpang INT NOT NULL,
    id_jadwal INT NOT NULL,
    nomor_gerbong INT NOT NULL,
    nomor_kursi VARCHAR(5) NOT NULL,
    tanggal_pemesanan DATE NOT NULL,
    status_pembayaran VARCHAR(20) NOT NULL,
    metode_pembayaran VARCHAR(30) NOT NULL,
    
    FOREIGN KEY (id_penumpang) REFERENCES penumpang(id_penumpang),
    FOREIGN KEY (id_jadwal) REFERENCES jadwal(id_jadwal)
);



